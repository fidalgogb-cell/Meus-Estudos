x = input('Digite algo: ')
tp = type(x)
n = x.isnumeric()
a = x.isalpha()
an = x.isalnum()
u = x.isupper()
l = x.islower()
c = x.istitle()
print('O tipo primitivo é: {}{}{}'.format('\033[1;33m', tp, '\033[m'))
print('É numérico? {}{}{}'.format('\033[1;33m', n, ' \033[m'))
print('É alfabético? {}{}{}'.format('\033[1;33m', a, ' \033[m'))
print('É alfanumérico? {}{}{}'.format('\033[1;33m', an, ' \033[m'))
print('Está em maiúsculas? {}{}{}'.format('\033[1;33m', u, ' \033[m'))
print('Está em minúsculas? {}{}{}'.format('\033[1;33m', l, ' \033[m'))
print('Está capitalizada? {}{}{}'.format('\033[1;33m', c, '\033[m'))
# Exemplo sem usar a máscara:
print('Só tem espaços?', '\033[1;33m', x.isspace(), '\033[m')
